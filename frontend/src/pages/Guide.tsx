export function Guide() {
  useDocumentTitle('دليل الاستخدام')
  const employee = useUser()
  const [scope, setScope] = useState<'mine' | 'all'>('mine')
  const shown = scope === 'mine' ? TOPICS.filter((t) => t.mine(employee)) : TOPICS
  return (
    <div className="guide">
      <header className="ph">
        <div>
          <h1><BookOpen size={26} /> دليل الاستخدام</h1>
          <p className="muted">خطوات قصيرة لكل عمل. أهلاً بك يا {employee.name.split(' ')[0]}.</p>
        </div>
        <Segmented<'mine' | 'all'> label="ما الذي تريد عرضه" value={scope} options={[{ value: 'mine', label: 'عملي أنا' }, { value: 'all', label: 'كل الأقسام' }]} onChange={setScope} />
      </header>
      <nav className="guide-toc card" aria-label="المحتويات">
        <a href="#g-work-map"><Stamp size={15}/>خريطة المهام والأختام</a>
        {shown.map((t) => <a key={t.key} href={`#g-${t.key}`}><t.icon size={15} />{t.title}</a>)}
      </nav>
      <WorkMap />
      {shown.map((t) => (
        <section key={t.key} id={`g-${t.key}`} className="card guide-topic">
          <div className="card-h"><span className="ico-round brand"><t.icon size={16} /></span><h2>{t.title}</h2>{t.to && t.mine(employee) && <Link to={t.to} className="link-btn card-h-action">افتح الصفحة</Link>}</div>
          <ol>{t.steps.map((s, i) => <li key={i}>{s}</li>)}</ol>
          {t.tip && <p className="guide-tip">{t.tip}</p>}
        </section>
      ))}
      <p className="muted guide-foot"><UserRound size={14} /> لم تجد جواب سؤالك هنا؟ اسأل مدير الفرع.</p>
    </div>
  )
}
